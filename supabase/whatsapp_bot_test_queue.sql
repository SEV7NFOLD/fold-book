-- Private one-recipient test-send queue shared by the admin API and Render worker.
create table if not exists public.whatsapp_bot_test_queue (
  id bigint generated by default as identity primary key,
  phone_number text not null check (phone_number ~ '^234[789][0-9]{9}$'),
  session text not null check (session in ('morning', 'evening')),
  status text not null default 'queued' check (status in ('queued', 'processing', 'sent', 'failed')),
  detail text,
  requested_at timestamptz not null default now(),
  processed_at timestamptz
);

create index if not exists whatsapp_bot_test_queue_pending_idx
  on public.whatsapp_bot_test_queue (requested_at, id)
  where status = 'queued';

alter table public.whatsapp_bot_test_queue enable row level security;
revoke all on public.whatsapp_bot_test_queue from public, anon, authenticated;
grant all on public.whatsapp_bot_test_queue to service_role;
grant usage, select on sequence public.whatsapp_bot_test_queue_id_seq to service_role;

-- Claim one row atomically so multiple worker instances cannot send the same test twice.
create or replace function public.claim_whatsapp_bot_test()
returns setof public.whatsapp_bot_test_queue
language sql
security invoker
set search_path = ''
as $$
  with next_job as (
    select id
    from public.whatsapp_bot_test_queue
    where status = 'queued'
    order by requested_at, id
    for update skip locked
    limit 1
  )
  update public.whatsapp_bot_test_queue as queued
  set status = 'processing'
  from next_job
  where queued.id = next_job.id
  returning queued.*;
$$;

revoke execute on function public.claim_whatsapp_bot_test() from public, anon, authenticated;
grant execute on function public.claim_whatsapp_bot_test() to service_role;

alter table public.whatsapp_bot_delivery_log
  drop constraint if exists whatsapp_bot_delivery_log_session_check;
alter table public.whatsapp_bot_delivery_log
  add constraint whatsapp_bot_delivery_log_session_check
  check (session in ('morning', 'evening', 'preview', 'test'));
